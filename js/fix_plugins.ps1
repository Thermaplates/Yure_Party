$content = Get-Content 'plugins.js' -Raw
$jsonPart = $content -replace '(?s).*var \$plugins\s*=\s*', '' -replace '(?s);\s*$', ''
$arr = ConvertFrom-Json $jsonPart

$out = "// Generated by RPG Maker.`r`n// Do not edit this file directly.`r`nvar `$plugins =`r`n[`r`n"
$first = $true
foreach ($item in $arr) {
    if (!$first) { $out += ",`r`n" }
    $first = $false
    $out += (ConvertTo-Json $item -Compress -Depth 10)
}
$out += "`r`n];"

Set-Content -Path 'plugins.js' -Value $out -Encoding UTF8
