import json
with open('c:/Users/Fauzi/Documents/Games/Yure Party/js/plugins.js', 'r', encoding='utf-8') as f:
    content = f.read()

start_idx = content.find('[')
end_idx = content.rfind(']') + 1

plugins = json.loads(content[start_idx:end_idx])

for p in plugins:
    if p['name'] == 'MOG_SceneMenu':
        p['parameters']['Skull X-Axis'] = '350'
        p['parameters']['Skull Y-Axis'] = '300'
        p['parameters']['Skull Scale'] = '1.00'

out = '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar ' + '$' + 'plugins =\n[\n'
lines = []
for p in plugins:
    lines.append(json.dumps(p, separators=(',', ':')))
out += ',\n'.join(lines)
out += '\n];\n'

with open('c:/Users/Fauzi/Documents/Games/Yure Party/js/plugins.js', 'w', encoding='utf-8') as f:
    f.write(out)
print('Fixed plugins.js without PowerShell interpolation!')
